"""What a Python tree looks like to something walking it.

What a neutral caller used to answer for itself and Python decides: what
pytest is told about a repository's tests, what a directory of Python is
called once it is one, and where a repository writes down the requirements
and the data files its packages need beside their code. Each answer is a
spelling -- ``__init__.py``, ``python_files``, a dot between package parts,
``[tool.setuptools.package-data]`` in a ``pyproject.toml`` -- and a
spelling of the language's is what a core is for.

Which directories hold tests, how a tier's directory is spelled and what a
walk passes over are not here: two Python repositories may differ on each,
so they are an adapter's configuration and are handed in.
"""

