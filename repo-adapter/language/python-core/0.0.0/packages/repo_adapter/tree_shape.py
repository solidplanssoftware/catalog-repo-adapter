def _declared_package_roots(*, declaration: dict) -> list[str]:
    """The directories a repository declares its packages are found under.

    `[tool.setuptools.packages.find] where = [...]`: the wrapper directory,
    which holds packages and nothing else.
    """
    packages = declaration.get("tool", {}).get("setuptools", {}).get("packages", {})
    if not isinstance(packages, dict):
        return []
    where = packages.get("find", {}).get("where", [])
    return [entry for entry in where if isinstance(entry, str)]


def package_base(*, directory: Path) -> Path | None:
    """The directory a package's dotted name is counted from, if one is declared.

    Which package an importer reaches a directory as is the owning repository's
    statement rather than a fact about the path: `cli/packages/cli` is imported
    as `cli`, not as `cli.packages.cli`, because `cli/pyproject.toml` says its
    packages are found under `packages/`. The nearest `pyproject.toml` at or
    above the directory decides, because that is the repository the directory
    belongs to.

    A repository that declares no such root answers None, and a caller counts
    from wherever it was already counting -- which is what every repository
    meant while its root was its package.
    """
    for candidate in (directory, *directory.parents):
        if not (candidate / _PACKAGING_METADATA).is_file():
            continue
        try:
            declaration = tomllib.loads(
                (candidate / _PACKAGING_METADATA).read_text(encoding="utf-8")
            )
        except (OSError, tomllib.TOMLDecodeError):
            return None
        for where in _declared_package_roots(declaration=declaration):
            base = (candidate / where).resolve()
            if directory == base or directory.is_relative_to(base):
                return base
        return None
    return None


def own_package_roots(*, directory: Path) -> list[Path]:
    """The directories the repository holding ``directory`` imports its packages from.

    Read off the packaging metadata nearest above the directory, which is
    that repository's: each directory it declares its packages are found
    under, or its root where it declares none -- which is what every
    repository meant while its root was its package. A tree with no such
    metadata answers nothing.
    """
    for candidate in (directory, *directory.parents):
        metadata = candidate / _PACKAGING_METADATA
        if not metadata.is_file():
            continue
        try:
            declaration = tomllib.loads(metadata.read_text(encoding="utf-8"))
        except (OSError, tomllib.TOMLDecodeError):
            return [candidate]
        declared = _declared_package_roots(declaration=declaration)
        return [(candidate / where).resolve() for where in declared] or [candidate]
    return []


def _import_root(*, directory: Path, repo_root: Path) -> Path:
    """The directory an import of the package at ``directory`` is counted from.

    The nearest directory above it that carries no ``__init__.py``, and no
    higher than the repository root: a package's dotted name is the chain of
    packages that contain it, and the first directory that is not one is
    where that chain starts. A directory outside the repository answers the
    root, which its caller then refuses.
    """
    current = directory
    while current != repo_root and repo_root in current.parents:
        parent = current.parent
        if parent == repo_root or not (parent / _PACKAGE_MARKER).is_file():
            return parent
        current = parent
    return repo_root


def resolve_package_name(*, directory: Path, repo_root: Path) -> str | None:
    """Return the dotted package name of a directory, or None if it is not one.

    A directory is a package when it carries an ``__init__.py``. Namespace
    packages are deliberately not recognized here: this answers for a caller
    naming a package to a packager, and a namespace portion has no single
    directory to name.

    The name is counted from the directory the owning repository declares its
    packages are found under. Counting from the root alone was right while a
    repository's root was its package, and named `manifest/packages/manifest`
    as `manifest.packages.manifest` once it was not -- which is a package
    nothing imports.

    Where the repository declares no such directory, the name is counted the
    way an import counts it: from the nearest directory above that is not
    itself a package. Only setuptools' declaration is read, and every other
    build backend finds a `src/` layout without being told, so a repository
    built with one of them declares nothing -- and counted from its root,
    `src/itsdangerous` was `src.itsdangerous`. A chain of packages reaching
    the repository root is counted from the root, as it always was.
    """
    if not (directory / _PACKAGE_MARKER).is_file():
        return None
    base = package_base(directory=directory) or _import_root(
        directory=directory, repo_root=repo_root
    )
    try:
        relative = directory.relative_to(base)
    except ValueError:
        return None
    if relative == Path("."):
        return None
    return ".".join(relative.parts)


def declared_language_requirements(
    *, repo_root: Path, include_development: bool = False
) -> list[str]:
    """Return the third-party requirements this repository declares.

    Read out of ``[project] dependencies``, which is where a Python repository
    already states what it needs installed. The strings come back as written --
    ``pydantic==2.8.2``, not ``pydantic`` -- because a publisher's specifier is
    part of what it declared, and narrowing it here would throw away the only
    place that information exists.

    ``include_development`` adds ``[dependency-groups]``. A publisher leaves it
    off: what a consumer needs in order to import and read vendored source is
    what that source requires at run time, not the tooling its own gate uses. A
    consumer checking its own declaration turns it on, because a repository
    that imports none of these at run time declares them exactly there --
    `shell_adapter` names `pydantic`, `PyYAML` and `tzdata` in its development
    group, for trees it only has to be able to read.

    A repository with no ``pyproject.toml``, or whose packaging metadata is not
    that file, contributes nothing.
    """
    pyproject = repo_root / _PACKAGING_METADATA
    if not pyproject.is_file():
        return []
    try:
        declaration = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return []

    project = declaration.get("project", {})
    stated: list[str] = list(project.get("dependencies", []) or [])
    if "dependencies" in (project.get("dynamic", []) or []):
        stated.extend(
            _dynamic_dependencies(
                repo_root=repo_root,
                declaration=declaration,
                include_generated=include_development,
            )
        )
    if include_development:
        groups = declaration.get("dependency-groups", {})
        if isinstance(groups, dict):
            for entries in groups.values():
                if isinstance(entries, list):
                    stated.extend(entries)
    return [
        entry.strip() for entry in stated if isinstance(entry, str) and entry.strip()
    ]


def declares_requirement(*, directory: Path, name: str) -> bool:
    """Whether the repository holding ``directory`` declares one distribution.

    Anywhere it declares requirements: its own, its vendored trees' and its
    development groups. Asked by name alone, whatever specifier, extra or
    marker the declaration carries, and without regard to case or to whether
    it is written with a hyphen or an underscore. A tree with no packaging
    metadata declares nothing.
    """

    def normalized(value: str) -> str:
        """A distribution name as every spelling of it compares equal."""
        return (
            re.split(r"[\s<>=!~;\[(@]", value.strip(), maxsplit=1)[0]
            .lower()
            .replace("_", "-")
        )

    for candidate in (directory, *directory.parents):
        if (candidate / _PACKAGING_METADATA).is_file():
            return normalized(name) in {
                normalized(entry)
                for entry in declared_language_requirements(
                    repo_root=candidate, include_development=True
                )
            }
    return False


def declared_path_sources(*, repo_root: Path) -> list[PathSource]:
    """Return the packages this repository tells uv to take from a path.

    Read out of ``[tool.uv.sources]``, which is where a Python repository states
    that a package is installed from a directory rather than from an index: an
    entry naming a ``path`` is one, and an entry naming a git url, an index or a
    workspace member is not. A source may be a list of tables selected by
    markers, and any of them naming a path makes the package one taken from a
    path. The path comes back as written, and the packages in the order the
    table states them.

    A repository with no ``pyproject.toml``, or one that is not valid TOML,
    declares none.
    """
    pyproject = repo_root / _PACKAGING_METADATA
    if not pyproject.is_file():
        return []
    try:
        declaration = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return []

    tool = declaration.get("tool", {})
    uv = tool.get("uv", {}) if isinstance(tool, dict) else {}
    sources = uv.get("sources", {}) if isinstance(uv, dict) else {}
    if not isinstance(sources, dict):
        return []
    found: list[PathSource] = []
    for name, source in sources.items():
        entries = source if isinstance(source, list) else [source]
        for entry in entries:
            path = entry.get("path") if isinstance(entry, dict) else None
            if isinstance(path, str) and path.strip():
                found.append(PathSource(package=str(name), path=path.strip()))
                break
    return found


#: One clause of ``requires-python``: an operator and a version, with the
#: ``.*`` a prefix match may end in.
_VERSION_CLAUSE = re.compile(
    r"^(?P<operator>===|==|~=|>=|<=|!=|>|<)\s*(?P<version>\d+(?:\.\d+)*)(?:\.\*)?$"
)

#: The operators whose clause names a version the repository admits and
#: none beneath it.
_FLOOR_OPERATORS = frozenset({">=", "~=", "==", "==="})


def language_version(*, repo_root: Path) -> str | None:
    """Return the lowest Python version this repository says it runs on.

    Read out of ``[project] requires-python``, which is where a Python
    repository states the versions it is written for. The statement is a span
    and the answer is one version, the lowest the span admits: the clause
    that sets a floor (``>=3.13``, ``~=3.13``, ``==3.13.*``), as far as it was
    written and no further than its patch, and the highest of them where
    several do. That is the version every line of the repository has to be
    valid in, so it is the one an adapter's rules are held to.

    ``None`` where no clause sets one -- a repository with no
    ``pyproject.toml`` or no ``requires-python``, one stating only what it
    stops at (``<4``), and a ``>`` clause, which names a version the
    repository does not admit. Resolving a specifier in full is a package
    manager's arithmetic and is not done here.
    """
    pyproject = repo_root / _PACKAGING_METADATA
    if not pyproject.is_file():
        return None
    try:
        declaration = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return None
    stated = _table(declaration, "project").get("requires-python")
    if not isinstance(stated, str):
        return None

    floors: list[tuple[int, ...]] = []
    for clause in stated.split(","):
        match = _VERSION_CLAUSE.match(clause.strip())
        if match is None or match["operator"] not in _FLOOR_OPERATORS:
            continue
        floors.append(tuple(int(part) for part in match["version"].split("."))[:3])
    if not floors:
        return None
    return ".".join(str(segment) for segment in max(floors))


def _requirements_in(*, path: Path) -> list[str]:
    """The requirements one requirements file states.

    Comments and blank lines are not requirements, and a line beginning with
    ``-`` is an option to the installer rather than a package -- ``-r`` naming
    another file, an index url, a flag. Reading one as a requirement would put
    a dash-prefixed string into a comparison against package names, where it
    could only ever fail to match.
    """
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    found: list[str] = []
    for line in lines:
        entry = line.split("#", 1)[0].strip()
        if not entry or entry.startswith("-"):
            continue
        found.append(entry)
    return found


def _table(document: object, *keys: str) -> dict[str, object]:
    """Walk a chain of nested tables, answering an empty one at the first miss.

    A parsed `pyproject.toml` is nested plain dicts, and reaching
    `[tool.setuptools.dynamic]` through them meant a `get` and an `isinstance`
    per level -- five pairs to read two keys, where the interesting part was
    the path and the noise was the checking.

    Nothing typed is available to replace it. `pyproject-metadata` models
    `[project]` and neither sees `[tool.*]` nor expands `dynamic`, so it
    answers `[]` here; `setuptools.config.pyprojecttoml.read_configuration`
    does expand it, but returns the two files merged into one list -- which is
    the distinction `include_generated` exists to make -- and setuptools marks
    that table's support beta. So the walk stays, and this is the walk.

    A missing key and a key holding something that is not a table are the same
    answer on purpose: both mean *this document does not declare that*, and a
    reader asking for a nested table has nothing different to do about a
    string it did not expect.
    """
    current = document
    for key in keys:
        if not isinstance(current, dict):
            return {}
        current = current.get(key, {})
    return current if isinstance(current, dict) else {}


def _dynamic_dependencies(
    *,
    repo_root: Path,
    declaration: dict[str, object],
    include_generated: bool,
) -> list[str]:
    """The requirements a project declares through setuptools' ``dynamic``.

    ``[project] dependencies`` is the one field a repository that vendors
    cannot write out in full: half of it is what its own code needs, and half
    is what the trees it fetched need, which nobody types. PEP 621 makes
    ``dynamic`` all-or-nothing per field, so both halves move into files and
    the pyproject names them -- the hand-written one and the generated one,
    which is the whole of what a person has to say.

    ``include_generated`` is which question is being asked. A publisher
    records what a consumer needs in order to import *its* source, and the
    generated file holds what somebody else's source needs -- carried here on
    its way to an installer and not this repository's to claim. A consumer
    asking whether its environment is complete counts it, because a
    requirement satisfied there is satisfied.
    """
    dependencies = _table(declaration, "tool", "setuptools", "dynamic", "dependencies")
    files = dependencies.get("file", [])
    # One file or several: setuptools accepts both spellings, and a caller
    # that handled only the list would read a repository naming one file as
    # declaring nothing.
    if isinstance(files, str):
        files = [files]
    if not isinstance(files, list):
        return []

    found: list[str] = []
    for entry in files:
        if not isinstance(entry, str) or not entry.strip():
            continue
        if not include_generated and entry.strip() == _VENDORED_REQUIREMENTS:
            continue
        found.extend(_requirements_in(path=repo_root / entry.strip()))
    return found


def render_vendored_requirements(
    *, repo_root: Path, requirements: list[str]
) -> VendoredRequirementsFile | None:
    """Render the file that states what this repository's vendored trees need.

    Sorted case-insensitively and de-duplicated by the line as written, so the
    file is a function of what was fetched rather than of the order it came
    back in. Case-insensitively because the record this is rendered from sorts
    by distribution name, which is lowercase by definition, and the same
    packages listed in two orders across two files is a diff nobody can read -- a
    generated file that moves for no reason is one nobody can read a diff of.
    Two requirements naming one package at different specifiers are left as
    two lines: resolving that disagreement is a package manager's work, and it
    already refuses the pair loudly, which is a better answer than one of them
    being silently dropped here.

    Always answered, even for a repository that vendored nothing. An empty
    list is a statement -- *these trees need nothing installed* -- and the
    alternative is a file that exists when a dependency happens to have one
    and is missing when it does not, which is the packaging metadata refusing
    to build in a clone that has not vendored yet.
    """
    seen: list[str] = []
    for entry in requirements:
        text = entry.strip()
        if text and text not in seen:
            seen.append(text)
    body = "".join(f"{entry}\n" for entry in sorted(seen, key=str.lower))
    return VendoredRequirementsFile(
        path=Path(_VENDORED_REQUIREMENTS),
        content=f"{_VENDORED_REQUIREMENTS_HEADER}{body}",
    )


def declared_package_data(*, repo_root: Path) -> list[PackagedFile]:
    """Return the files this repository declares as package data.

    Read out of ``[tool.setuptools.package-data]``, which is where a Python
    repository already states them so that a wheel carries them. Reading the
    declaration keeps one owner for it; a repository with no
    ``pyproject.toml``, or whose packaging metadata is not this file,
    contributes nothing.

    A package is looked for under each directory the repository declares its
    packages are found in, and under the repository root where it declares
    none. The destination is counted from that same directory, because that
    is where an importer counts the package from and so where the code
    reading the file looks: `packages/dev_tool/dev.app.yml` is read as
    `dev_tool/dev.app.yml`. Counting both from the root was right while a
    repository's root was its package, and found no file at all once the
    packages moved under `packages/`.
    """
    pyproject = repo_root / _PACKAGING_METADATA
    if not pyproject.is_file():
        return []

    document = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    declared = (
        document.get("tool", {}).get("setuptools", {}).get("package-data", {}) or {}
    )
    bases = [
        repo_root / where for where in _declared_package_roots(declaration=document)
    ] or [repo_root]

    found: list[PackagedFile] = []
    for package, patterns in sorted(declared.items()):
        for base in bases:
            package_dir = base / Path(*str(package).split("."))
            for pattern in patterns if isinstance(patterns, list) else []:
                for path in sorted(package_dir.glob(str(pattern))):
                    if not path.is_file():
                        continue
                    found.append(
                        PackagedFile(
                            source=path,
                            destination=path.parent.relative_to(base).as_posix(),
                        )
                    )
    return found
