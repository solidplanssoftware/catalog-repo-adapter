def tier_isolation_arguments(*, isolated_tiers: Sequence[str]) -> list[str]:
    """Return the pytest arguments that hold the isolated tiers to starting no process.

    None where nothing is isolated, and the run is then plain pytest.
    """
    if not isolated_tiers:
        return []
    arguments = ["-p", _TIER_ISOLATION_PLUGIN]
    for tier in isolated_tiers:
        arguments.extend(["--isolated-tier", tier])
    return arguments


